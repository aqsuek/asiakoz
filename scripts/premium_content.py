def get_category(dx_id: str) -> str:
    return DX_CATEGORY.get(dx_id, "diagnostics")


def build_premium(
    dx_id: str,
    lang: str,
    copy: dict[str, Any],
    city_name: str,
    address: str,
) -> dict[str, Any]:
    """Merge category defaults, dx overrides, and page copy into premium payload."""
    cat = get_category(dx_id)
    base = CATEGORY.get(cat, CATEGORY["diagnostics"])[lang]
    out: dict[str, Any] = {}

    for key, val in base.items():
        if isinstance(val, list):
            out[key] = list(val)
        elif isinstance(val, str):
            out[key] = val.format(city=city_name, address=address)
        else:
            out[key] = val

    # dx-specific override
    dx_extra = DX_EXTRA.get(dx_id, {}).get(lang, {})
    for key, val in dx_extra.items():
        if key in out and isinstance(out[key], list) and isinstance(val, list):
            out[key] = val + out[key]
        else:
            out[key] = val.format(city=city_name, address=address) if isinstance(val, str) else val

    # Use copy lead as first what paragraph if not overridden
    lead = copy.get("lead", "").format(city=city_name, address=address)
    what = [lead] + out.get("what_extra", [])
    out["what_paras"] = what

    if not out.get("symptoms") and "symptoms" in copy:
        pass
    elif out.get("symptoms"):
        pass

    # Hero facts from copy
    facts = copy.get("facts", [])
    hero_facts = [(b, t.format(city=city_name, address=address) if "{city}" in t else t) for b, t in facts[:4]]
    while len(hero_facts) < 4:
        hero_facts.append(
            ("Диагностика", "от 20 000 ₸") if lang == "ru" else ("Диагностика", "20 000 ₸-дан")
        )
    out["hero_facts"] = hero_facts[:4]

    # How steps — extend copy steps to 6 if needed
    steps = [(t, p.format(city=city_name, address=address)) for t, p in copy.get("steps", [])]
    generic_steps_ru = [
        ("Диагностика", "Подтверждаем диагноз и оцениваем глаз целиком."),
        ("Обсуждение", "Объясняем варианты лечения и ожидаемый результат."),
        ("Лечение", "Консервативное или хирургическое — по показаниям."),
        ("Контроль", f"Повторные визиты в филиале {city_name}."),
    ]
    generic_steps_kk = [
        ("Диагностика", "Диагноз расталады."),
        ("Талқылау", "Ем нұсқалары түсіндіріледі."),
        ("Ем", "Көрсеткіш бойынша."),
        ("Бақылау", f"{city_name} филиалында."),
    ]
    pool = generic_steps_ru if lang == "ru" else generic_steps_kk
    while len(steps) < 6:
        idx = len(steps)
        if idx < len(pool):
            steps.append(pool[idx])
        else:
            break
    out["how_steps"] = steps[:6]

    out["name"] = copy.get("name", "")
    svc = CATEGORY_SERVICES.get(cat, {}).get(lang, RETINA_SERVICES_RU if lang == "ru" else RETINA_SERVICES_KK)
    out["related_services"] = svc
    from premium_deep import get_deep_section

    out["deep"] = get_deep_section(dx_id, lang)
    return out
