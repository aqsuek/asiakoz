def get_deep_section(dx_id: str, lang: str) -> dict[str, Any] | None:
    """Return localized deep section payload for rendering."""
    key = DEEP_BY_DX.get(dx_id)
    if key and key in DEEP_CUSTOM:
        raw = DEEP_CUSTOM[key]
    else:
        cat = None
        from premium_content import get_category

        cat = get_category(dx_id)
        raw = DEEP_BY_CATEGORY.get(cat)
    if not raw:
        return None

    def pick(field: str) -> Any:
        return raw[field][lang] if isinstance(raw[field], dict) else raw[field]

    return {
        "id": raw["id"],
        "title": pick("title"),
        "subtitle": pick("subtitle"),
        "intro": pick("intro"),
        "headers": pick("headers"),
        "rows": pick("rows"),
        "cards": pick("cards"),
        "note": pick("note"),
        "aria": pick("aria"),
    }


def deep_section_html(deep: dict[str, Any] | None) -> str:
    if not deep:
        return ""
    intro_parts = []
    for i, p in enumerate(deep["intro"]):
        if i:
            intro_parts.append(f'<p style="margin-top:12px;">{p}</p>')
        else:
            intro_parts.append(f"<p>{p}</p>")
    intro = "".join(intro_parts)
    headers = "".join(f"<th scope=\"col\">{h}</th>" for h in deep["headers"])
    rows_html = []
    for row in deep["rows"]:
        cells = "".join(f"<td>{c}</td>" for c in row[1:])
        rows_html.append(f"<tr><th scope=\"row\">{row[0]}</th>{cells}</tr>")
    cards = []
    for title, items in deep["cards"]:
        lis = "".join(f"<li>{it}</li>" for it in items)
        cards.append(f"<article><h3>{title}</h3><ul>{lis}</ul></article>")
    note = f'<p class="section-note">{deep["note"]}</p>' if deep.get("note") else ""
    return f"""    <section class="section" id="{deep['id']}">
      <h2 class="section-title">{deep['title']}</h2>
      <p class="section-subtitle">{deep['subtitle']}</p>
{intro}
      <div class="iol-table-wrap" role="region" aria-label="{deep['aria']}" tabindex="0">
        <table class="iol-table">
          <thead><tr>{headers}</tr></thead>
          <tbody>{''.join(rows_html)}</tbody>
        </table>
      </div>
      <div class="iol-compare">{''.join(cards)}</div>
      {note}
    </section>"""
