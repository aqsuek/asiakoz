def insert_city_switch(path: Path, dx_id: str, city: str, lang: str) -> None:
    if not path.exists():
        return
    html = path.read_text(encoding="utf-8")
    if 'class="city-switch"' in html:
        return
    block = city_switch_html(dx_id, city, lang)
    html2, n = re.subn(
        r'(</nav>\s*)(<section class="(?:seo-hero|lp-hero|spa-hero))',
        rf"\1    {block}\n    \2",
        html,
        count=1,
    )
    if n:
        path.write_text(html2, encoding="utf-8")
        print(f"switch: {path.relative_to(ROOT)}")


def main() -> None:
    written = 0
    for dx_id, dx in DIAGNOSES.items():
        for city in dx["cities"]:
            for lang in ("ru", "kk"):
                if city in dx.get("skip_write", []) and dx_id != "peresadka-rogovitsy":
                    continue
                folder = dx["folder"](city)
                dest = ROOT / ("kk" if lang == "kk" else "") / folder / "index.html"
                if lang == "ru":
                    dest = ROOT / folder / "index.html"
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(render_page(dx_id, city, lang), encoding="utf-8")
                written += 1
                print(f"write: {dest.relative_to(ROOT)}")

    insert_city_switch(ROOT / "katarakta-almaty" / "index.html", "katarakta", "almaty", "ru")
    insert_city_switch(ROOT / "lazer-almaty" / "index.html", "lazer", "almaty", "ru")
