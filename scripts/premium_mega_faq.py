def get_mega_faq(
    dx_id: str,
    lang: str,
    name: str,
    city: str,
    wa: str,
    wa_disp: str = "",
) -> list[tuple[str, str]]:
    """Return list of (question, answer_html) for rendering."""
    cat = get_category(dx_id)
    pool = list(CATEGORY_MEGA.get(cat, RETINA_FAQ_RU if cat == "retina" else []))
    pool.extend(COMMON_TAIL_RU)
    out: list[tuple[str, str]] = []
    disp = wa_disp or f"+{wa[:1]} {wa[1:4]} {wa[4:7]} {wa[7:9]} {wa[9:]}"
    for item in pool:
        q = _p(item["q"][lang], lang, city, name, wa, disp)
        paras = item["p"][lang]
        body = "".join(f"<p>{_p(p, lang, city, name, wa, disp)}</p>" for p in paras)
        out.append((q, body))
    return out[:20]


def mega_faq_html(items: list[tuple[str, str]], lang: str) -> str:
    title = "Сұрақ-жауап" if lang == "kk" else "Вопросы и ответы"
    blocks = []
    for i, (q, body) in enumerate(items):
        open_attr = " open" if i == 0 else ""
        blocks.append(f"      <details{open_attr}><summary>{q}</summary>{body}</details>")
    return f"""    <section class="section faq" id="faq">
      <h2 class="section-title">{title}</h2>
{chr(10).join(blocks)}
    </section>"""
